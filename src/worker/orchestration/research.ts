import { CROSS_DOMAIN_BY_VENUE, SEED_KIND_LABELS, SEED_KIND_TO_QLOO_TYPE, VENUE_CATEGORY_LABELS, type VenueCategory } from "../../shared/constants/vocabulary";
import type {
  CulturalTheme,
  EvidenceProvenance,
  PartnershipCandidate,
  ResearchEvent,
  ResearchRequest,
  ResearchRun,
  ResearchStep,
  ResearchStepId,
  ResolvedSeed,
} from "../../shared/schemas/evidence";
import { QlooError, type QlooTransport } from "../integrations/qloo/client";
import { contributions, isThematicTag, normalizeEntities, normalizeName, normalizeTags, resolvedLocality, strengthOf } from "../integrations/qloo/normalize";

/**
 * Bounded research planner. It is a fixed, typed sequence of tool choices with conditional
 * branches (skip, broaden, fall back), not an open-ended agent: every branch is enumerated here,
 * every call is counted against a per-run budget, and every output carries provenance.
 */

export const MAX_SEEDS_PER_RUN = 3;

export const TOOLS = {
  resolve_entity: { route: "/search", purpose: "Match a cultural reference to a Qloo entity" },
  resolve_tag: { route: "/v2/tags", purpose: "Match a venue category to a Qloo tag" },
  recommend_venues: { route: "/v2/insights", purpose: "Rank venues in a location by affinity to the references" },
  cross_domain: { route: "/v2/insights", purpose: "Find related entities in another domain for a collaboration theme" },
  taste_tags: { route: "/v2/insights", purpose: "Describe the references' audience with taste tags" },
} as const;

/**
 * Authenticated tag searches found no exact Qloo tag for these labels. We search for Qloo's nearest
 * established category instead and disclose the substitution in the run's limitations.
 */
const QLOO_CATEGORY_QUERY: Partial<Record<VenueCategory, string>> = {
  clothing_boutique: "Clothing store",
  plant_shop: "Plant nursery",
};

/**
 * Live tag searches return several tags with the same name (for example a cafe category, a
 * restaurant genre, and a hotel amenity). We prefer the plain place category, then a plain place
 * genre, then any other place tag.
 */
function placeTagRank(t: { id: string; type?: string }): number {
  if (/:category:place:[a-z0-9_]+$/.test(t.id)) return 0;
  if (/:genre:place:[a-z0-9_]+$/.test(t.id)) return 1;
  if (/(^|:)place(:|$)/.test(t.type ?? "") || t.id.includes(":place:")) return 2;
  return 3;
}

const STEP_LABELS: Record<ResearchStepId, string> = {
  resolve_seeds: "Matching your cultural references",
  resolve_category: "Matching the venue category",
  find_venues: "Ranking venues by cultural affinity",
  broaden_location: "Widening the search area",
  cultural_bridge: "Building a cultural bridge",
};

// Errors that end the run. Reaching the call budget is not among them: we keep what was found
// and skip the remaining steps, because partial evidence with a stated limit beats none.
const FATAL: ReadonlySet<QlooError["code"]> = new Set(["NOT_CONFIGURED", "UNTRUSTED_BASE_URL", "AUTH", "RATE_LIMITED", "QUOTA_EXHAUSTED", "UPSTREAM_UNAVAILABLE"]);
const isBudget = (error: unknown) => error instanceof QlooError && error.code === "BUDGET_EXHAUSTED";

// Tag IDs for venue categories are stable, so a short per-isolate cache saves quota without
// storing any user data or bulk Qloo content.
const categoryCache = new Map<string, { id: string; name: string; at: string; expires: number }>();
const CATEGORY_TTL_MS = 6 * 60 * 60 * 1000;
export function clearCategoryCache(): void {
  categoryCache.clear();
}

export interface ResearchDeps {
  transport: QlooTransport;
  mode: "live" | "fixture";
  callBudget: number;
  runId: string;
  now?: () => number;
  emit?: (event: ResearchEvent) => void | Promise<void>;
}

const compact = (s: string) => normalizeName(s).replace(/\s+/g, "");
/**
 * `candidate` is Qloo's name, `input` what the visitor typed. Live book titles carry subtitles
 * ("Braiding Sweetgrass: Indigenous Wisdom, …"), so an exact match on the main title before the
 * colon also counts, but only when the visitor typed no subtitle of their own.
 */
export function sameName(candidate: string, input: string): boolean {
  const x = compact(candidate);
  const y = compact(input);
  if (x === "" || y === "") return false;
  if (x === y || x === `${y}s` || y === `${x}s`) return true;
  const colon = candidate.indexOf(":");
  return colon > 0 && !input.includes(":") && compact(candidate.slice(0, colon)) === y;
}

export async function runResearch(request: ResearchRequest, deps: ResearchDeps): Promise<ResearchRun> {
  const now = deps.now ?? Date.now;
  const started = now();
  const iso = () => new Date(now()).toISOString();
  const kind: EvidenceProvenance["kind"] = deps.mode === "live" ? "qloo_observed" : "synthetic_demo";
  const fixtureNote = deps.mode === "fixture" ? "Fixture mode: fictional data generated by Room for Both, not a Qloo response." : undefined;
  const provenance = (endpoint: string, req: string): EvidenceProvenance => ({
    kind,
    endpoint,
    request: req,
    retrievedAt: iso(),
    ...(fixtureNote ? { note: fixtureNote } : {}),
  });

  const steps: ResearchStep[] = [];
  const limitations: string[] = [
    "Qloo affinity describes aggregate taste associations. It does not show foot traffic, sales, rent, permission, or a venue's willingness to partner.",
    "Affinity scores are relative to the query that produced them; compare results by position rather than by small score differences.",
    "Qloo lists venues of every size, including national chains; check whether each one fits an independent partnership.",
  ];
  if (deps.mode === "fixture") {
    limitations.unshift("Fixture mode: every cultural result in this run is fictional demonstration data. No Qloo request was made.");
  }

  const emit = async (event: ResearchEvent) => {
    if (deps.emit) await deps.emit(event);
  };
  const record = async (step: ResearchStep) => {
    steps.push(step);
    await emit({ type: "step", step });
  };
  const timed = async <T>(fn: () => Promise<T>): Promise<{ value: T; ms: number; calls: number }> => {
    const t0 = now();
    const c0 = deps.transport.callsUsed;
    const value = await fn();
    return { value, ms: Math.max(0, now() - t0), calls: deps.transport.callsUsed - c0 };
  };

  let budgetReached = false;
  const skipForBudget = (id: ResearchStepId, tool: string) =>
    record({ id, tool, status: "skipped", calls: 0, summary: "Skipped: this run's call budget was reached.", durationMs: 0 });

  const planned: ResearchStepId[] = ["resolve_seeds", "resolve_category", "find_venues", "cultural_bridge"];
  await emit({ type: "plan", mode: deps.mode, steps: planned.map((id) => ({ id, label: STEP_LABELS[id] })) });

  // 1. Resolve the guest's cultural references to Qloo entities.
  const seeds: ResolvedSeed[] = [];
  const seedInputs = request.seeds.slice(0, MAX_SEEDS_PER_RUN);
  if (request.seeds.length > MAX_SEEDS_PER_RUN) {
    limitations.push(`Only the first ${MAX_SEEDS_PER_RUN} cultural references are used per run to stay within the call budget.`);
  }
  if (seedInputs.length === 0) {
    await record({ id: "resolve_seeds", tool: "resolve_entity", status: "skipped", calls: 0, summary: "No cultural references were supplied.", durationMs: 0 });
  } else {
    const r = await timed(async () => {
      for (const input of seedInputs) {
        const type = SEED_KIND_TO_QLOO_TYPE[input.kind];
        const req = `Entity search for “${input.label}” (${SEED_KIND_LABELS[input.kind].toLowerCase()})`;
        const notSearched = () =>
          seeds.push({ input, status: "unresolved", entity: null, alternatives: [], provenance: { ...provenance("/search", req), note: "Not searched: the run's call budget was reached." } });
        if (budgetReached) {
          notSearched();
          continue;
        }
        try {
          const payload = await deps.transport.get("/search", { query: input.label, types: type, take: 5 });
          const candidates = normalizeEntities(payload, 5);
          const exact = candidates.filter((c) => sameName(c.name, input.label));
          const chosen = exact[0] ?? candidates[0] ?? null;
          const status: ResolvedSeed["status"] = exact.length > 0 ? "exact" : chosen ? "uncertain" : "unresolved";
          seeds.push({
            input,
            status,
            entity: chosen ? { id: chosen.id, name: chosen.name, type: chosen.type } : null,
            alternatives: candidates.filter((c) => c.id !== chosen?.id).slice(0, 4).map((c) => ({ id: c.id, name: c.name })),
            provenance: provenance("/search", req),
          });
        } catch (error) {
          if (isBudget(error)) {
            budgetReached = true;
            notSearched();
            continue;
          }
          if (error instanceof QlooError && FATAL.has(error.code)) throw error;
          seeds.push({ input, status: "unresolved", entity: null, alternatives: [], provenance: { ...provenance("/search", req), note: "The lookup failed; this reference was skipped." } });
        }
      }
    });
    const exactCount = seeds.filter((s) => s.status === "exact").length;
    for (const s of seeds.filter((x) => x.status === "uncertain")) {
      limitations.push(`“${s.input.label}” matched only approximately (closest: “${s.entity?.name}”), so it was not used as a signal. Confirm the intended reference to include it.`);
    }
    for (const s of seeds.filter((x) => x.status === "unresolved")) {
      limitations.push(`“${s.input.label}” was not found${deps.mode === "live" ? " in Qloo" : ""}, so it was not used.`);
    }
    await record({
      id: "resolve_seeds",
      tool: "resolve_entity",
      status: "done",
      calls: r.calls,
      summary: `${exactCount} of ${seedInputs.length} references matched exactly.`,
      durationMs: r.ms,
    });
  }
  const signalSeeds = seeds.filter((s) => s.status === "exact" && s.entity !== null);
  const signalIds = signalSeeds.map((s) => s.entity?.id ?? "");
  const seedNames = new Map(signalSeeds.map((s) => [(s.entity?.id ?? "").toLowerCase(), s.input.label]));

  // 2. Resolve the venue category to a Qloo tag (exact matches only).
  const categoryLabel = VENUE_CATEGORY_LABELS[request.venueCategory];
  const categoryQuery = QLOO_CATEGORY_QUERY[request.venueCategory] ?? categoryLabel;
  const proxyNote = categoryQuery !== categoryLabel ? ` Qloo has no “${categoryLabel}” tag, so venues are searched as “${categoryQuery}”, its nearest category.` : "";
  let categoryTag: ResearchRun["categoryTag"] = null;
  const cacheKey = `${deps.mode}:${request.venueCategory}`;
  const cached = deps.mode === "live" ? categoryCache.get(cacheKey) : undefined;
  if (cached && cached.expires > now()) {
    categoryTag = {
      id: cached.id,
      name: cached.name,
      status: "exact",
      provenance: { ...provenance("/v2/tags", `Tag search for “${categoryQuery}”`), retrievedAt: cached.at, note: "Reused from a recent identical lookup." },
    };
    if (proxyNote) limitations.push(proxyNote.trim());
    await record({ id: "resolve_category", tool: "resolve_tag", status: "done", calls: 0, summary: `Matched “${categoryQuery}” (cached).`, durationMs: 0 });
  } else if (budgetReached) {
    await skipForBudget("resolve_category", "resolve_tag");
  } else {
    try {
      const r = await timed(() => deps.transport.get("/v2/tags", { "filter.query": categoryQuery, take: 10 }));
      const tags = normalizeTags(r.value, 10);
      const matches = tags.filter((t) => sameName(t.name, categoryQuery)).sort((a, b) => placeTagRank(a) - placeTagRank(b));
      const chosen = matches[0] ?? null;
      if (chosen) {
        categoryTag = { id: chosen.id, name: chosen.name, status: "exact", provenance: provenance("/v2/tags", `Tag search for “${categoryQuery}”`) };
        if (deps.mode === "live") categoryCache.set(cacheKey, { id: chosen.id, name: chosen.name, at: iso(), expires: now() + CATEGORY_TTL_MS });
        if (proxyNote) limitations.push(proxyNote.trim());
      } else {
        limitations.push(`No Qloo tag exactly matched “${categoryQuery}”, so venue discovery was skipped rather than guessing a category.`);
      }
      await record({
        id: "resolve_category",
        tool: "resolve_tag",
        status: chosen ? "done" : "failed",
        calls: r.calls,
        summary: chosen ? `Matched “${categoryQuery}” to a Qloo tag.` : `No exact tag for “${categoryQuery}”.`,
        durationMs: r.ms,
      });
    } catch (error) {
      if (isBudget(error)) {
        budgetReached = true;
        await skipForBudget("resolve_category", "resolve_tag");
      } else {
        if (error instanceof QlooError && FATAL.has(error.code)) throw error;
        limitations.push("The venue category lookup failed, so venue discovery was skipped.");
        await record({ id: "resolve_category", tool: "resolve_tag", status: "failed", calls: 1, summary: "Category lookup failed.", durationMs: 0 });
      }
    }
  }

  // 3. Rank venues in the market by affinity to the matched references.
  let candidates: PartnershipCandidate[] = [];
  let venueSearch: ResearchRun["venueSearch"] = null;
  if (!categoryTag) {
    await record({
      id: "find_venues",
      tool: "recommend_venues",
      status: "skipped",
      calls: 0,
      summary: budgetReached ? "Skipped: this run's call budget was reached." : "Skipped: no confirmed venue category.",
      durationMs: 0,
    });
  } else if (budgetReached) {
    await skipForBudget("find_venues", "recommend_venues");
  } else {
    if (signalIds.length === 0) {
      limitations.push("No reference matched exactly, so venues are listed without a taste signal and their order may mostly reflect general popularity.");
    }
    const locations = request.neighborhood ? [request.neighborhood, request.city] : [request.city];
    for (const [i, location] of locations.entries()) {
      const stepId: ResearchStepId = i === 0 ? "find_venues" : "broaden_location";
      const req = `Places tagged “${categoryTag.name}” in ${location}${signalIds.length ? `, ranked by affinity to ${signalSeeds.map((s) => `“${s.input.label}”`).join(", ")}` : ""}`;
      try {
        const r = await timed(() =>
          deps.transport.get("/v2/insights", {
            "filter.type": "urn:entity:place",
            "filter.tags": categoryTag?.id,
            "filter.location.query": location,
            "signal.interests.entities": signalIds.length ? signalIds : undefined,
            "feature.explainability": signalIds.length ? true : undefined,
            take: request.maxCandidates,
          }),
        );
        const returned = normalizeEntities(r.value, request.maxCandidates);
        const venues = returned.filter((v) => !v.closed);
        if (venues.length < returned.length) {
          const n = returned.length - venues.length;
          limitations.push(`${n} venue${n === 1 ? "" : "s"} that Qloo marks as closed ${n === 1 ? "was" : "were"} left out.`);
        }
        const locality = resolvedLocality(r.value);
        if (venues.length > 0) {
          limitations.push(
            locality && normalizeName(locality) !== normalizeName(location)
              ? `Qloo matched “${location}” to the area “${locality}”. Some venues may sit outside the neighbourhood you had in mind; check each address.`
              : `Venues are ranked within the area Qloo matched for “${location}”; check each address before reaching out.`,
          );
        }
        const prov = provenance("/v2/insights", req);
        candidates = venues.map((venue, idx) => ({
          venue: { id: venue.id, name: venue.name, type: venue.type, popularity: venue.popularity, affinity: venue.affinity, tags: venue.tags, address: venue.address, location: venue.location },
          category: request.venueCategory,
          rank: idx + 1,
          strength: signalIds.length ? strengthOf(venue.affinity) : "unscored",
          contributions: contributions(venue.explainability, seedNames),
          sharedTags: [],
          provenance: prov,
        }));
        if (venues.length > 0) venueSearch = { location, categoryTagId: categoryTag.id, categoryName: categoryTag.name, take: request.maxCandidates };
        await record({
          id: stepId,
          tool: "recommend_venues",
          status: "done",
          calls: r.calls,
          summary: venues.length ? `Found ${venues.length} ${categoryLabel.toLowerCase()} candidates in ${location}.` : `No ${categoryLabel.toLowerCase()} results in ${location}.`,
          durationMs: r.ms,
        });
        if (venues.length > 0) break;
      } catch (error) {
        if (isBudget(error)) {
          budgetReached = true;
          await skipForBudget(stepId, "recommend_venues");
          break;
        }
        if (error instanceof QlooError && FATAL.has(error.code)) throw error;
        const unknownPlace = error instanceof QlooError && error.code === "BAD_REQUEST";
        await record({
          id: stepId,
          tool: "recommend_venues",
          status: "failed",
          calls: 1,
          summary: unknownPlace ? `Qloo did not recognise “${location}”.` : `Venue search in ${location} failed.`,
          durationMs: 0,
        });
      }
    }
    if (candidates.length === 0) limitations.push("No venue candidates were found. You can still evaluate a host you choose yourself.");
  }

  // 4. Cultural bridge: what else the references' audience gravitates to.
  const themes: CulturalTheme[] = [];
  let bridgeDomain: string | null = null;
  // Tag names observed on bridge results; a venue sharing one of them gives an evidence-linked overlap.
  const bridgeTags = new Set<string>();
  if (signalIds.length === 0) {
    await record({ id: "cultural_bridge", tool: "taste_tags", status: "skipped", calls: 0, summary: "Skipped: needs at least one exactly matched reference.", durationMs: 0 });
  } else if (budgetReached) {
    await skipForBudget("cultural_bridge", "taste_tags");
  } else {
    const cross = CROSS_DOMAIN_BY_VENUE[request.venueCategory];
    const seedList = signalSeeds.map((s) => `“${s.input.label}”`).join(", ");
    // Fixture runs must never describe their invented associations as Qloo's.
    const associates = deps.mode === "live" ? "Qloo associates" : "In this fictional fixture run, the demonstration data associates";
    // Unscoped taste tags mix every domain (payment cards next to TV keywords in live results), so we
    // scope them to the entity types Qloo itself reported for the matched references.
    const parentTypes = [...new Set(signalSeeds.map((s) => s.entity?.type ?? "").filter((t) => t.startsWith("urn:entity:")))];
    const t0 = now();
    const c0 = deps.transport.callsUsed;
    let tool: string = cross ? "cross_domain" : "taste_tags";
    let fellBack = false;
    let failed = false;

    if (cross) {
      try {
        const payload = await deps.transport.get("/v2/insights", { "filter.type": cross.type, "signal.interests.entities": signalIds, take: 8 });
        const items = normalizeEntities(payload, 8);
        const prov = provenance("/v2/insights", `${cross.noun} with affinity to ${seedList}`);
        if (items.length) {
          bridgeDomain = cross.type;
          themes.push({
            id: "cross-domain",
            title: cross.title,
            basis: "cross_domain",
            rationale: `${associates} ${seedList} with these ${cross.noun}. A ${categoryLabel.toLowerCase()} collaboration could be framed around them. This is a creative starting point, not evidence that either business's customers will respond.`,
            items: items.map((e) => ({
              id: e.id,
              name: e.name,
              type: e.type,
              affinity: e.affinity,
              strength: strengthOf(e.affinity),
              tags: e.tags.filter(isThematicTag).slice(0, 6).map((t) => t.name),
            })),
            provenance: prov,
            interpretation: "derived_rule",
          });
          const tagCounts = new Map<string, number>();
          for (const e of items) {
            for (const t of e.tags.filter(isThematicTag)) {
              tagCounts.set(t.name, (tagCounts.get(t.name) ?? 0) + 1);
              bridgeTags.add(normalizeName(t.name));
            }
          }
          const recurring = [...tagCounts.entries()].filter(([, n]) => n >= 2).sort((a, b) => b[1] - a[1]).slice(0, 6);
          if (recurring.length) {
            themes.push({
              id: "recurring-tags",
              title: "Recurring taste signals",
              basis: "taste_tags",
              rationale: `Tags that appear on two or more of the ${cross.noun} above. Counted directly from the returned tags; no scores are implied.`,
              items: recurring.map(([name]) => ({ id: `recurring:${normalizeName(name)}`, name, type: "tag", affinity: null, strength: "unscored" as const })),
              provenance: prov,
              interpretation: "derived_rule",
            });
          }
        } else {
          fellBack = true;
        }
      } catch (error) {
        if (isBudget(error)) budgetReached = true;
        else if (error instanceof QlooError && FATAL.has(error.code)) throw error;
        // Qloo answers 400 when none of the references carry signal in the target domain (seen live
        // for a brand-only reference and books). Taste tags are the documented next-best bridge.
        else if (error instanceof QlooError && error.code === "BAD_REQUEST") fellBack = true;
        else failed = true;
      }
      if (fellBack) limitations.push(`Qloo returned no ${cross.noun} linked to ${seedList}, so the bridge uses taste tags instead.`);
    }

    if ((!cross || fellBack) && !budgetReached) {
      tool = "taste_tags";
      try {
        const payload = await deps.transport.get("/v2/insights", {
          "filter.type": "urn:tag",
          "signal.interests.entities": signalIds,
          "filter.parents.types": parentTypes.length ? parentTypes : undefined,
          take: 8,
        });
        const tags = normalizeTags(payload, 8).filter(isThematicTag);
        for (const t of tags) bridgeTags.add(normalizeName(t.name));
        if (tags.length) {
          themes.push({
            id: "taste-tags",
            title: "Shared taste signals",
            basis: "taste_tags",
            rationale: `${associates} ${seedList} with these taste tags. They suggest a theme for the collaboration; they do not describe either business's actual customers.`,
            items: tags.map((t) => ({ id: t.id, name: t.name, type: t.type ?? "tag", affinity: t.affinity, strength: strengthOf(t.affinity) })),
            provenance: provenance("/v2/insights", `Taste tags with affinity to ${seedList}`),
            interpretation: "derived_rule",
          });
        }
      } catch (error) {
        if (isBudget(error)) budgetReached = true;
        else if (error instanceof QlooError && FATAL.has(error.code)) throw error;
        else failed = true;
      }
    }

    candidates = candidates.map((c) => ({
      ...c,
      sharedTags: c.venue.tags.filter((t) => isThematicTag(t) && bridgeTags.has(normalizeName(t.name))).map((t) => t.name).slice(0, 8),
    }));
    const calls = deps.transport.callsUsed - c0;
    if (themes.length === 0 && budgetReached && calls === 0) {
      await skipForBudget("cultural_bridge", tool);
    } else {
      await record({
        id: "cultural_bridge",
        tool,
        status: themes.length ? "done" : "failed",
        calls,
        summary: themes.length
          ? `Built ${themes.length} theme${themes.length === 1 ? "" : "s"} from Qloo results${fellBack ? " (taste tags after an empty cross-domain lookup)" : ""}.`
          : failed
            ? "The cultural bridge lookup failed."
            : budgetReached
              ? "Stopped: this run's call budget was reached."
              : "Qloo returned no related results.",
        durationMs: Math.max(0, now() - t0),
      });
    }
  }

  if (budgetReached) {
    limitations.push(`This run reached its limit of ${deps.callBudget} upstream calls, so later steps were skipped and the results are partial.`);
  }

  return {
    runId: deps.runId,
    mode: deps.mode,
    request,
    steps,
    seeds,
    categoryTag,
    candidates,
    themes,
    limitations,
    callsUsed: deps.transport.callsUsed,
    callBudget: deps.callBudget,
    durationMs: Math.max(0, now() - started),
    venueSearch,
    bridgeDomain,
  };
}
