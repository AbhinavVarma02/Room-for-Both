import { CROSS_DOMAIN_BY_VENUE, bridgeDomain } from "../../shared/constants/vocabulary";
import type { BaselineRequest, BaselineResult, EvidenceProvenance, SensitivityRequest, SensitivityResult, SensitivityVariant, VenueBridge, VenueBridgeRequest } from "../../shared/schemas/evidence";
import { QlooError, type QlooTransport } from "../integrations/qloo/client";
import { strengthOf } from "../../shared/domain/affinity";
import { clip, contributions, isThematicTag, normalizeEntities } from "../integrations/qloo/normalize";

/**
 * Single-call follow-ups to a research run. Each is its own request so it carries its own CPU and
 * call budget, and each repeats only identifiers the earlier run already returned.
 */

/** How deep the category-only list goes, so we can say where taste-ranked venues fall without signals. */
export const BASELINE_DEPTH = 10;

interface FollowupDeps {
  transport: QlooTransport;
  mode: "live" | "fixture";
  now?: () => number;
}

function provenanceFor(deps: FollowupDeps, request: string): EvidenceProvenance {
  return {
    kind: deps.mode === "live" ? "qloo_observed" : "synthetic_demo",
    endpoint: "/v2/insights",
    // Same 300-character cap as the schema, so long reference labels cannot invalidate the response.
    request: clip(request, 300),
    retrievedAt: new Date((deps.now ?? Date.now)()).toISOString(),
    ...(deps.mode === "fixture" ? { note: "Fixture mode: fictional data generated by Room for Both, not a Qloo response." } : {}),
  };
}

export async function runBaseline(request: BaselineRequest, deps: FollowupDeps): Promise<BaselineResult> {
  const payload = await deps.transport.get("/v2/insights", {
    "filter.type": "urn:entity:place",
    "filter.tags": request.categoryTagId,
    "filter.location.query": request.location,
    take: BASELINE_DEPTH,
  });
  const returned = normalizeEntities(payload, BASELINE_DEPTH);
  const venues = returned.filter((v) => !v.closed);
  const limitations = [
    "Category-only order is Qloo's ranking for the category and area with no reference to score against. It is not a measure of fit or of demand.",
  ];
  if (deps.mode === "fixture") limitations.unshift("Fixture mode: every venue in this comparison is fictional demonstration data. No Qloo request was made.");
  if (venues.length < returned.length) limitations.push(`${returned.length - venues.length} venue(s) that Qloo marks as closed were left out, as in the taste-informed run.`);
  const provenance = provenanceFor(deps, `Places tagged “${request.categoryName}” in ${request.location}, with no taste signal (category-only)`);
  return {
    mode: deps.mode,
    request,
    depth: BASELINE_DEPTH,
    candidates: venues.map((v, i) => ({
      venue: { id: v.id, name: v.name, type: v.type, popularity: v.popularity, affinity: null, tags: v.tags, address: v.address, location: v.location },
      category: request.venueCategory,
      rank: i + 1,
      strength: "unscored",
      contributions: [],
      sharedTags: [],
      provenance,
    })),
    provenance,
    callsUsed: deps.transport.callsUsed,
    limitations,
  };
}

export class NoVenueDomainError extends Error {}

export async function runVenueBridge(request: VenueBridgeRequest, deps: FollowupDeps): Promise<VenueBridge> {
  const cross = bridgeDomain(request.domain) ?? CROSS_DOMAIN_BY_VENUE[request.venueCategory];
  if (!cross) throw new NoVenueDomainError("This kind of venue has no cross-domain lookup.");
  const prov = provenanceFor(deps, `${cross.noun} with affinity to the venue “${request.venueName}” itself`);
  const limitations = [
    `These ${cross.noun} describe the aggregate taste Qloo links to the venue. They do not describe its stock, its programming, or its customers' purchases.`,
  ];
  if (deps.mode === "fixture") limitations.unshift("Fixture mode: these results are fictional demonstration data. No Qloo request was made.");
  let items: VenueBridge["items"] = [];
  try {
    const payload = await deps.transport.get("/v2/insights", { "filter.type": cross.type, "signal.interests.entities": request.venueId, take: 8 });
    items = normalizeEntities(payload, 8).map((e) => ({
      id: e.id,
      name: e.name,
      type: e.type,
      affinity: e.affinity,
      strength: strengthOf(e.affinity),
      tags: e.tags.filter(isThematicTag).slice(0, 6).map((t) => t.name),
    }));
  } catch (error) {
    // Qloo answers 400 when the signal carries nothing in the target domain; that is an empty answer, not a failure.
    if (!(error instanceof QlooError && error.code === "BAD_REQUEST")) throw error;
  }
  if (items.length === 0) limitations.push(`${deps.mode === "live" ? "Qloo" : "The fictional data"} returned no ${cross.noun} for this venue, so only the guest's side of the bridge is available.`);
  return {
    mode: deps.mode,
    venueId: request.venueId,
    venueName: request.venueName,
    domain: cross.type,
    title: cross.title,
    noun: cross.noun,
    items,
    provenance: prov,
    callsUsed: deps.transport.callsUsed,
    limitations,
  };
}

// Credential and quota failures end the whole check; anything else (including a spent retry budget) fails one variant.
const FATAL_SENSITIVITY = new Set(["AUTH", "NOT_CONFIGURED", "QUOTA_EXHAUSTED", "UNTRUSTED_BASE_URL"]);

/**
 * Repeats the taste-informed venue search once per reference, each time without it. Every variant
 * keeps the original category, area, depth, and reference order, so any difference comes from the
 * missing reference alone. A failed variant is reported as failed, never filled in.
 */
export async function runSensitivity(request: SensitivityRequest, deps: FollowupDeps): Promise<SensitivityResult> {
  const variants: SensitivityVariant[] = [];
  for (const omitted of request.signals) {
    const kept = request.signals.filter((s) => s.id !== omitted.id);
    const seedNames = new Map(kept.map((s) => [s.id.toLowerCase(), s.label]));
    const provenance = provenanceFor(
      deps,
      `Places tagged “${request.categoryName}” in ${request.location}, ranked by affinity to ${kept.map((s) => `“${s.label}”`).join(", ")} (without “${omitted.label}”)`,
    );
    try {
      const payload = await deps.transport.get("/v2/insights", {
        "filter.type": "urn:entity:place",
        "filter.tags": request.categoryTagId,
        "filter.location.query": request.location,
        "signal.interests.entities": kept.map((s) => s.id),
        "feature.explainability": true,
        take: request.take,
      });
      const venues = normalizeEntities(payload, request.take).filter((v) => !v.closed);
      variants.push({
        omitted: omitted.label,
        status: "done",
        provenance,
        candidates: venues.map((v, i) => ({
          venue: { id: v.id, name: v.name, type: v.type, popularity: v.popularity, affinity: v.affinity, tags: v.tags, address: v.address, location: v.location },
          category: request.venueCategory,
          rank: i + 1,
          strength: strengthOf(v.affinity),
          contributions: contributions(v.explainability, seedNames),
          sharedTags: [],
          provenance,
        })),
      });
    } catch (error) {
      if (error instanceof QlooError && FATAL_SENSITIVITY.has(error.code)) throw error;
      variants.push({ omitted: omitted.label, status: "failed", provenance, candidates: [] });
    }
  }
  const limitations = [
    "Each variant drops one reference and keeps everything else the same. Differences describe Qloo's ranking for that query, not demand or fit.",
    "Affinity scores are relative to their own query, so compare positions across variants rather than scores.",
  ];
  if (deps.mode === "fixture") limitations.unshift("Fixture mode: every list here is fictional demonstration data. No Qloo request was made.");
  return { mode: deps.mode, request, variants, callsUsed: deps.transport.callsUsed, limitations };
}
